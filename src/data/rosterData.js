export function searchRoster(query) {
  const q = (query || '').trim().toLowerCase();
  if (!q) return [];
  const results = [];
  for (const [roll, data] of Object.entries(BATCH_ROSTER)) {
    const rollLower = roll.toLowerCase();
    const nameLower = data.n.toLowerCase();
    if (rollLower.includes(q) || nameLower.includes(q) || rollLower.slice(3).includes(q)) {
      results.push({
        rollNo: roll,
        name: data.n,
        section: data.s
      });
      if (results.length >= 12) break; // Top 12 matches
    }
  }
  return results;
}
